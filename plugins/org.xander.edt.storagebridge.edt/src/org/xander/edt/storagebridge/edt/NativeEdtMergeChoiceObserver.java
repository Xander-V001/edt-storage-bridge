package org.xander.edt.storagebridge.edt;

import java.util.ArrayList;
import java.util.Collection;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.eclipse.core.runtime.IProgressMonitor;
import org.eclipse.core.runtime.IStatus;
import org.eclipse.core.runtime.Status;
import org.eclipse.core.runtime.jobs.Job;
import com._1c.g5.v8.bm.core.IBmTransaction;
import com._1c.g5.v8.bm.integration.IBmTask;
import com._1c.g5.v8.dt.compare.core.ComparisonProcessHandle;
import com._1c.g5.v8.dt.compare.core.ComparisonTreeNodeEvent;
import com._1c.g5.v8.dt.compare.core.IComparisonManager;
import com._1c.g5.v8.dt.compare.core.IComparisonSession;
import com._1c.g5.v8.dt.compare.model.ComparisonNode;
import com._1c.g5.v8.dt.compare.model.MergeSettings;
import com._1c.g5.v8.dt.compare.model.TopComparisonNode;

/**
 * Observes native EDT comparison tree changes BY NODE ID, never by EDT file
 * contents or independent comparison logic. A read-only BM task resolves
 * each changed node's current checkbox, merge rule and top-level native FQN.
 *
 * IMPORTANT: model events can be generated by EDT itself (initialization,
 * recomputation, filters), not only by a user's click. Neither a checked
 * state nor MERGE_PROCESS_FINISHED proves individual changes were applied.
 * The last callback may race merge start, and unobserved default settings are
 * not in this event journal. Thus this is a diagnostic receipt of OBSERVED
 * model settings; it cannot yet advance APPLIED or assert exact KEPT_LOCAL.
 */
public final class NativeEdtMergeChoiceObserver implements AutoCloseable {
    /** Immutable state captured from the native comparison tree. */
    public record NodeChoice(long nodeId, String ownerSymlink, String nodeType,
            boolean checked, String mergeRule, boolean userRule,
            boolean nestedExcluded, boolean customMerge, String eventType) {
        public NodeChoice {
            ownerSymlink = ownerSymlink == null || ownerSymlink.isBlank()
                ? "(EDT owner unknown)" : ownerSymlink;
        }

        public String display() {
            return ownerSymlink + "  |  " + (checked ? "[x]" : "[ ]")
                + "  |  " + mergeRule + (nestedExcluded ? " / nested excluded" : "")
                + (customMerge ? " / CUSTOM" : "")
                + (userRule ? " / user rule" : "")
                + "  |  " + nodeType + " #" + nodeId + " (" + eventType + ")";
        }
    }

    public record Snapshot(List<NodeChoice> nodes, int deliveredEvents,
            int filteredWithoutDifferences, int unreadEvents,
            boolean observedBeforeMerge, boolean complete,
            boolean sessionAvailable) {
        public Snapshot { nodes = List.copyOf(nodes); }

        public String summary() {
            long checked = nodes.stream().filter(NodeChoice::checked).count();
            long skipped = nodes.size() - checked;
            return "узлов " + nodes.size() + " (флаг включён " + checked
                + ", выключен " + skipped + "), событий " + deliveredEvents
                + ", без подтверждённых различий отфильтровано "
                + filteredWithoutDifferences
                + ", не прочитано " + unreadEvents
                + (complete ? ", события обработаны до Merge"
                    : ", снимок НЕполный/неподтверждённый")
                + "; только наблюдение, результат применения UNKNOWN";
        }

        public List<String> rows(int limit) {
            List<String> rows = new ArrayList<>();
            for (NodeChoice choice : nodes) {
                if (rows.size() >= limit) break;
                rows.add(choice.display());
            }
            if (nodes.size() > limit) {
                rows.add("... еще " + (nodes.size() - limit) + " записей");
            }
            return List.copyOf(rows);
        }
    }

    private static final int MAX_NODES = 100_000;
    private final IComparisonManager manager;
    private final ComparisonProcessHandle handle;
    private final IComparisonSession.IComparisonTreeListener listener;
    private final Job captureJob;

    private IComparisonSession session;
    private boolean closed;
    private boolean mergeStarted;
    private boolean finishedCapture;
    private boolean sessionAvailable;
    private boolean initialBaselineCaptured;
    private int deliveredEvents;
    private int failures;
    private final Map<Long, String> queued = new LinkedHashMap<>();
    private final Map<Long, NodeChoice> observed = new HashMap<>();
    // Only diagnostic: tree events also include unchanged nested nodes.
    // Track unique IDs excluded by EDT's own native comparison flags so the
    // diagnostic output explains why its count differs from event count.
    private final Set<Long> withoutDifferences = new HashSet<>();

    public NativeEdtMergeChoiceObserver(IComparisonManager manager,
            ComparisonProcessHandle handle) {
        this.manager = manager;
        this.handle = handle;
        this.captureJob = new Job("Storage Bridge: observe native EDT Merge node events") {
            @Override protected IStatus run(IProgressMonitor monitor) {
                captureQueued(monitor);
                return Status.OK_STATUS;
            }
        };
        captureJob.setSystem(true);
        this.listener = events -> {
            synchronized (NativeEdtMergeChoiceObserver.this) {
                if (closed || mergeStarted || events == null) return;
                for (ComparisonTreeNodeEvent event : events) {
                    if (event == null) continue;
                    deliveredEvents++;
                    long id = event.getNodeId();
                    if (event.getType() == ComparisonTreeNodeEvent.EventType.REMOVED) {
                        observed.remove(id);
                        withoutDifferences.remove(id);
                        queued.remove(id);
                    } else if (queued.size() < MAX_NODES) {
                        queued.put(id, event.getType().name());
                    } else {
                        failures++;
                    }
                }
                scheduleCapture();
            }
        };
    }

    /**
     * Subscribe as soon as the native manager has created its session;
     * waiting for COMPARISON_PROCESS_FINISHED loses initial EDT default states.
     * No modification of EDT view or comparison tree is performed.
     */
    public synchronized void onStatus(String status) {
        if (closed) return;
        if (status.startsWith("MERGE_PROCESS_")
                && (status.endsWith("_STARTED")
                    || status.endsWith("_FINISHED"))
                || "COMPARISON_MERGE_PROCESS_CANCELLED".equals(status)) {
            mergeStarted = true;
            // An empty event queue is NOT evidence unless EDT provided a
            // session and at least one native baseline was captured.
            finishedCapture = sessionAvailable && initialBaselineCaptured
                && queued.isEmpty() && failures == 0
                && captureJob.getState() == Job.NONE;
            captureJob.cancel();
            return;
        }
        if (mergeStarted || session != null) return;
        try {
            IComparisonSession found = manager.getComparisonSession(handle);
            if (found != null) {
                found.addComparisonTreeListener(listener);
                session = found;
                sessionAvailable = true;
                // EDT often created its first nodes before registration.
                // Read changed merge-settings nodes as an initial baseline;
                // subsequent native tree events update the same per-id map.
                scheduleCapture();
            }
        } catch (RuntimeException | LinkageError ex) {
            failures++;
        }
    }

    private void scheduleCapture() {
        if (!closed && !mergeStarted && session != null) {
            try { captureJob.schedule(0L); }
            catch (RuntimeException ignored) { /* job may already be running */ }
        }
    }

    private void captureQueued(IProgressMonitor progress) {
        for (;;) {
            IComparisonSession current;
            Map<Long, String> batch;
            boolean captureInitial;
            synchronized (this) {
                if (closed || mergeStarted || session == null) return;
                current = session;
                batch = new LinkedHashMap<>(queued);
                queued.clear();
                captureInitial = !initialBaselineCaptured;
            }
            try {
                // All node access is inside native EDT's own READ-ONLY task.
                Map<Long, NodeChoice> sampled =
                    current.runComparisonTreeReadonlyTask(new IBmTask<Map<Long, NodeChoice>>() {
                        @Override public Object getId() { return null; }
                        @Override public Object getServiceId() { return null; }
                        @Override public String getName() { return "Inspect native EDT choices"; }
                        @Override public Map<Long, NodeChoice> execute(
                                IBmTransaction tx, IProgressMonitor monitor) {
                            if (!tx.isReadOnly()) {
                                throw new IllegalStateException("EDT comparison tree is writable");
                            }
                            Map<Long, NodeChoice> data = new HashMap<>();
                            if (captureInitial) {
                                Collection<Long> preexisting =
                                    current.getNodesWithChangedMergeSettings();
                                for (Long id : preexisting) {
                                    if (id != null && data.size() < MAX_NODES) {
                                        readNode(current, id, "INITIAL", data);
                                    }
                                }
                            }
                            for (Map.Entry<Long, String> e : batch.entrySet()) {
                                if (monitor.isCanceled()) break;
                                readNode(current, e.getKey(), e.getValue(), data);
                            }
                            return data;
                        }
                    });
                synchronized (this) {
                    if (closed || mergeStarted) return;
                    // A node may be re-computed by EDT after a previous
                    // event. Remove a stale observation if its current native
                    // flags no longer prove MAIN/OTHER differences.
                    for (var entry : sampled.entrySet()) {
                        Long id = entry.getKey();
                        NodeChoice choice = entry.getValue();
                        if (choice == null) {
                            observed.remove(id);
                            withoutDifferences.add(id);
                        } else {
                            withoutDifferences.remove(id);
                            observed.put(id, choice);
                        }
                    }
                    initialBaselineCaptured = true;
                    if (queued.isEmpty()) return;
                }
            } catch (RuntimeException | LinkageError ex) {
                synchronized (this) {
                    failures++;
                    if (!mergeStarted && !closed) queued.putAll(batch);
                }
                return;
            }
        }
    }

    private static void readNode(IComparisonSession session, long nodeId,
            String event, Map<Long, NodeChoice> result) {
        ComparisonNode node = session.getNode(nodeId);
        if (node == null) {
            result.put(nodeId, null);
            return;
        }
        // CRITICAL: DoNotMerge / unchecked is normal for an UNCHANGED
        // descendant of an affected top-level object. The comparison tree
        // emits COMPARISON_FINISHED events for such descendants too. Read
        // EDT's own consolidated comparison flags BEFORE merge settings;
        // never infer that an unchecked unchanged node was kept locally.
        // hasDiffsMainOther also includes partial/one-sided objects.
        var flags = node.getComparisonFlags();
        if (flags == null || !flags.hasDiffsMainOther()) {
            result.put(nodeId, null);
            return;
        }
        MergeSettings settings = node.getMergeSettings();
        if (settings == null) {
            result.put(nodeId, null);
            return;
        }
        TopComparisonNode top = session.getTopNodeOf(node);
        String owner = top == null ? null : top.getOtherSymlink();
        if (owner == null || owner.isBlank()) {
            owner = top == null ? null : top.getMainSymlink();
        }
        String type = node.eClass() == null ? "Node"
            : node.eClass().getName();
        result.put(nodeId, new NodeChoice(nodeId, owner, type,
            settings.isMustBeMerged(), String.valueOf(settings.getMergeRule()),
            settings.isMergeRuleSetByUser(),
            settings.isHaveChildrenExcludedFromMerge(),
            settings.getCustomSettings() != null, event));
    }

    public synchronized Snapshot snapshot() {
        List<NodeChoice> nodes = observed.values().stream()
            .sorted(java.util.Comparator.comparing(NodeChoice::ownerSymlink)
                .thenComparingLong(NodeChoice::nodeId))
            .toList();
        return new Snapshot(nodes, deliveredEvents,
            withoutDifferences.size(), queued.size() + failures,
            mergeStarted, finishedCapture, sessionAvailable);
    }

    public String summary() { return snapshot().summary(); }

    @Override public synchronized void close() {
        if (closed) return;
        closed = true;
        captureJob.cancel();
        if (session != null) {
            try { session.removeComparisonTreeListener(listener); }
            catch (RuntimeException | LinkageError ignored) {
                // EDT may already have destroyed the native session.
            }
            session = null;
        }
    }
}
